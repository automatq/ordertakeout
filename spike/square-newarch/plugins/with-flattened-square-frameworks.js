const fs = require("node:fs/promises");
const path = require("node:path");

const { withDangerousMod, withXcodeProject } = require("expo/config-plugins");

/**
 * Copy Square's nested frameworks up to the app's own Frameworks directory.
 *
 * Square ships its iOS dependencies *inside* its frameworks:
 *
 *   SquareInAppPaymentsSDK.framework/Frameworks/CorePaymentCard.framework
 *   SquareBuyerVerificationSDK.framework/Frameworks/ThreeDS_SDK.framework
 *
 * Both Square binaries link `@rpath/CorePaymentCard.framework/CorePaymentCard`,
 * and dyld resolves @rpath from the binary doing the loading. The payments SDK
 * finds it — that is its own nested directory. The buyer verification SDK does
 * not: CorePaymentCard is nested under its *sibling*, so `@loader_path/Frameworks`
 * misses it and the app dies at launch before a line of JavaScript runs:
 *
 *   dyld: Library not loaded: @rpath/CorePaymentCard.framework/CorePaymentCard
 *     Referenced from: .../SquareBuyerVerificationSDK.framework/…
 *
 * Neither framework is a published pod — `pod trunk` has no record of either —
 * so there is nothing to add to the Podfile. Flattening them into
 * `App.app/Frameworks` puts them on `@executable_path/Frameworks`, which every
 * binary in the bundle already searches.
 *
 * Square ships a `setup` script inside the framework that does this same
 * flattening, and their config plugin adds a phase to run it. We are not
 * duplicating that out of ignorance — their phase runs before the frameworks
 * exist and therefore does nothing. See PODFILE_HOOK below for why, and why the
 * fix has to live in post_install rather than in a config plugin.
 *
 * Written against "nested frameworks" in general rather than these two names: the
 * same packaging turns up in other vendor SDKs, and a rule that knows only two
 * filenames goes stale the moment Square adds a third.
 */

const SCRIPT_NAME = "harina-flatten-frameworks.sh";
const PHASE_NAME = "[Harina] Flatten nested vendor frameworks";

/**
 * A `post_integrate` hook appended to the Podfile.
 *
 * The phase has to run *after* `[CP] Embed Pods Frameworks`, and there are two
 * wrong answers before the right one.
 *
 * A config plugin cannot do it: plugins write the pbxproj during `prebuild`,
 * CocoaPods adds its phases later, so anything a plugin adds necessarily lands
 * in front of them. That is exactly why Square's own
 * `[CP] Square In-App Payments SDK Setup` phase — which runs a `setup` script
 * shipped inside the framework that does this same flattening — silently does
 * nothing. Confirmed in a build log: it runs immediately before
 * `[CP] Embed Pods Frameworks`, finds an empty directory, and exits 0.
 *
 * `post_install` is also too early, which is less obvious. CocoaPods runs the
 * podfile post_install hooks and only *then* integrates the user project, so
 * `[CP] Embed Pods Frameworks` does not exist yet when they fire. Re-appending
 * the phase there moves it, but the embed phase is still added after it.
 * Verified the same way — the reorder took effect and changed nothing.
 *
 * `post_integrate` runs after integration, and is the first point where the
 * embed phase is actually present to be ordered against.
 */
const PODFILE_HOOK = `  # Added by plugins/with-flattened-square-frameworks.js
  post_integrate do |installer|
    installer.aggregate_targets.each do |aggregate_target|
      user_project = aggregate_target.user_project
      next if user_project.nil?

      user_project.native_targets.each do |native_target|
        phase = native_target.build_phases.find do |build_phase|
          build_phase.respond_to?(:name) && build_phase.name == '${PHASE_NAME}'
        end
        next if phase.nil?

        # Re-appending moves it behind [CP] Embed Pods Frameworks.
        native_target.build_phases.delete(phase)
        native_target.build_phases << phase
      end

      user_project.save
    end
  end

`;

/**
 * The phase runs this from a file rather than inlining it.
 *
 * Not a style choice. The `xcode` library writes `shellScript` into the pbxproj
 * escaping backslashes and quotes but passing newlines through raw, and
 * CocoaPods' parser rejects a raw newline inside a quoted string. Escaping the
 * newline ourselves does not help — the library escapes the backslash we add and
 * the string terminates early instead. A one-line phase invoking a file sidesteps
 * all of it, matches what CocoaPods does for its own phases, and has the side
 * benefit that the script can be run by hand when debugging a build.
 */
const SCRIPT = `#!/bin/sh
# Generated by plugins/with-flattened-square-frameworks.js — do not edit.
set -e

FRAMEWORKS="\${BUILT_PRODUCTS_DIR}/\${FRAMEWORKS_FOLDER_PATH}"
[ -d "\${FRAMEWORKS}" ] || exit 0

for outer in "\${FRAMEWORKS}"/*.framework; do
  [ -d "\${outer}/Frameworks" ] || continue

  for inner in "\${outer}/Frameworks"/*.framework; do
    [ -d "\${inner}" ] || continue
    name=$(basename "\${inner}")

    # Already flattened, by an earlier target or a previous incremental build.
    if [ -e "\${FRAMEWORKS}/\${name}" ]; then
      continue
    fi

    echo "note: flattening \${name} out of $(basename "\${outer}")"
    cp -R "\${inner}" "\${FRAMEWORKS}/"

    # Copying invalidates the signature. Simulator builds sign with "-" or not at
    # all; device and distribution builds must be re-signed or iOS refuses to
    # launch the app.
    if [ -n "\${EXPANDED_CODE_SIGN_IDENTITY}" ] && [ "\${EXPANDED_CODE_SIGN_IDENTITY}" != "-" ]; then
      codesign --force --preserve-metadata=identifier,entitlements,flags --timestamp=none --sign "\${EXPANDED_CODE_SIGN_IDENTITY}" "\${FRAMEWORKS}/\${name}"
    fi
  done
done
`;

module.exports = function withFlattenedSquareFrameworks(config) {
  config = withDangerousMod(config, [
    "ios",
    async (cfg) => {
      const root = cfg.modRequest.platformProjectRoot;
      await fs.writeFile(path.join(root, SCRIPT_NAME), SCRIPT, { mode: 0o755 });

      const podfilePath = path.join(root, "Podfile");
      const podfile = await fs.readFile(podfilePath, "utf8");
      if (!podfile.includes("with-flattened-square-frameworks")) {
        /* Inserted ahead of post_install purely so the two hooks read in the
           order they run. post_integrate is a sibling, not nested inside it. */
        const anchor = "  post_install do |installer|\n";
        if (!podfile.includes(anchor)) {
          throw new Error(
            "Could not find the post_install hook in the Podfile — the Expo template changed, and the framework-flattening phase would silently run too early.",
          );
        }
        await fs.writeFile(podfilePath, podfile.replace(anchor, PODFILE_HOOK + anchor));
      }

      return cfg;
    },
  ]);

  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;

    /* `prebuild --clean` regenerates the project, but a plain prebuild reuses it.
       Adding the phase twice would run the copy twice. */
    const phases = project.hash?.project?.objects?.PBXShellScriptBuildPhase ?? {};
    const alreadyAdded = Object.values(phases).some(
      (phase) => phase && phase.name && phase.name.includes(PHASE_NAME),
    );
    if (alreadyAdded) return cfg;

    /* Appended last so it runs after Xcode's own "Embed Frameworks" phase —
       there is nothing to flatten until the frameworks have been copied in. */
    project.addBuildPhase([], "PBXShellScriptBuildPhase", PHASE_NAME, null, {
      shellPath: "/bin/sh",
      shellScript: `"$SRCROOT/${SCRIPT_NAME}"`,
    });

    return cfg;
  });
};
