const { withAndroidManifest, withDangerousMod, AndroidConfig } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

/**
 * Let release builds talk to a local dev server, and nothing else.
 *
 * Android has blocked cleartext HTTP by default since API 28. The debug
 * manifest opts back in wholesale, which is why `npx expo run:android` works
 * and a release build silently fails every request — the app loads, then shows
 * "no connection" forever with nothing in the log to explain it.
 *
 * Rather than turn cleartext on globally, this permits it for two named hosts:
 * `localhost`, which reaches the machine over `adb reverse tcp:3000 tcp:3000`,
 * and `10.0.2.2`, which is the host as seen from an emulator. Every other
 * destination — including the real API — stays HTTPS-only, so shipping this by
 * accident does not weaken production.
 *
 * Testing untethered over Wi-Fi means adding that machine's LAN address to
 * DEV_HOSTS. Deliberately not done here: a hardcoded IP in a committed config
 * is wrong the next time anyone joins a different network.
 */
const DEV_HOSTS = ["localhost", "10.0.2.2"];

const XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-dev-cleartext.js — do not edit by hand. -->
<network-security-config>
  <!-- base-config must come first: Android's schema is base, then domains,
       then debug-overrides, and a parser that trips on the order silently
       leaves you with the platform default. -->
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
${DEV_HOSTS.map((h) => `    <domain includeSubdomains="false">${h}</domain>`).join("\n")}
  </domain-config>
</network-security-config>
`;

module.exports = function withDevCleartext(config) {
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app/src/main/res/xml");
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, "network_security_config.xml"), XML);
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$["android:networkSecurityConfig"] = "@xml/network_security_config";
    return cfg;
  });
};
