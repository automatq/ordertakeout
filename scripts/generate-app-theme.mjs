#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Generate the mobile apps' colour tokens from app/globals.css.
 *
 * React Native cannot read CSS custom properties, so the apps need the palette
 * as a TypeScript object. Copying it by hand is what we did first, and within a
 * day the apps had drifted: the brand red was #9E3136 in both of them and
 * #ce3f23 on the web, along with a green and an amber that appear nowhere in
 * the palette at all. Nobody noticed, because "close enough" is exactly how
 * this fails.
 *
 * globals.css stays the single source of truth — it is where the tokens are
 * documented and where a designer would change them — and this only ever
 * reads. Both the light @theme block and the [data-theme="dark"] block are
 * emitted, and a token present in one but not the other is an error: that is a
 * screen which renders correctly in daylight and breaks at night. Run it after touching @theme; CI runs it and fails on a diff, so a
 * palette change that forgets the apps cannot merge.
 *
 *   node scripts/generate-app-theme.mjs
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const APPS = ["apps/staff-mobile", "apps/customer-mobile"];

/** `--color-status-new-soft` → `statusNewSoft` */
const camel = (token) =>
  token
    .replace(/^--color-/, "")
    .replace(/-([a-z0-9])/g, (_, character) => character.toUpperCase());

const css = readFileSync(join(root, "app/globals.css"), "utf8");

function readBlock(label, pattern) {
  const block = pattern.exec(css);
  if (!block) throw new Error(`No ${label} block in app/globals.css.`);

  const entries = [...block[1].matchAll(/^\s*(--color-[a-z0-9-]+):\s*([^;]+);/gm)].map(
    ([, token, value]) => [camel(token), value.trim()],
  );
  if (entries.length === 0) throw new Error(`No --color-* tokens found in ${label}.`);

  /* A non-literal value — var(), color-mix() — cannot cross into React Native,
     and emitting it would produce a string the app silently renders as black.
     Better to stop and make somebody decide. */
  for (const [name, value] of entries) {
    if (!/^#[0-9a-f]{3,8}$/i.test(value)) {
      throw new Error(
        `Token "${name}" is "${value}" in ${label}, which React Native cannot use. ` +
          `Give it a literal hex value, or teach this script how to resolve it.`,
      );
    }
  }
  return entries;
}

const light = readBlock("@theme", /@theme\s*\{(.*?)\n\}/s);
const dark = readBlock('[data-theme="dark"]', /\[data-theme="dark"\]\s*\{(.*?)\n\}/s);

/* A token that exists in one theme and not the other is a screen that renders
   correctly in daylight and breaks at night, or the reverse — and nobody tests
   both. Fail here instead. */
const lightNames = new Set(light.map(([name]) => name));
const darkNames = new Set(dark.map(([name]) => name));
const missing = [
  ...[...lightNames].filter((n) => !darkNames.has(n)).map((n) => `${n} (missing from dark)`),
  ...[...darkNames].filter((n) => !lightNames.has(n)).map((n) => `${n} (missing from light)`),
];
if (missing.length > 0) {
  throw new Error(`Light and dark palettes disagree:\n  ${missing.join("\n  ")}`);
}

const longest = Math.max(...light.map(([name]) => name.length));
const render = (entries) =>
  entries.map(([name, value]) => `    ${name.padEnd(longest)}: "${value}",`).join("\n");

const file = `// Generated by scripts/generate-app-theme.mjs from app/globals.css.
// Do not edit. Change the token there and re-run the script.
//
// React Native cannot read CSS custom properties, so the palette is mirrored
// here. globals.css is the source of truth; this file is an output, and CI
// fails if it is stale.

export const palettes = {
  light: {
${render(light)}
  },
  dark: {
${render(dark)}
  },
} as const;

export type Scheme = keyof typeof palettes;
export type Palette = (typeof palettes)[Scheme];
export type ColorToken = keyof Palette;

/** Light, for anything that has to name a colour outside a React tree. */
export const tokens = palettes.light;
`;

for (const app of APPS) {
  writeFileSync(join(root, app, "src/tokens.generated.ts"), file);
  console.log(`wrote ${app}/src/tokens.generated.ts (${light.length} tokens x 2 themes)`);
}
